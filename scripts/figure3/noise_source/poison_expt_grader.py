#!/usr/bin/env python3
"""
Poison Experiment Grader: Evaluates how well the Cell Sieve recovered poisoned labels.
"""
import argparse
import pandas as pd

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--truth-key", required=True, help="Path to the _truth_key.csv generated by the poison injector.")
    parser.add_argument("--flagged-csv", required=True, help="Path to the flagged_misannotations.csv generated by the sieve.")
    args = parser.parse_args()

    # 1. Load the data
    truth_df = pd.read_csv(args.truth_key)
    flagged_df = pd.read_csv(args.flagged_csv)

    # Total number of poisoned cells injected
    total_poisoned = truth_df["is_poisoned"].sum()
    total_clean = len(truth_df) - total_poisoned

    # 2. Merge the flagged cells with their hidden truth
    merged_df = flagged_df.merge(truth_df, on="cell_barcode", how="inner")

    # ... (Load truth_df and flagged_df, then merge into merged_df) ...

    # 1. How many cells are flagged as suspicious
    total_flagged = len(merged_df)
    
    # Split into Poisoned (True Positives) and Clean (False Positives)
    true_positives = merged_df[merged_df["is_poisoned"] == True]
    false_positives = merged_df[merged_df["is_poisoned"] == False]

    # 2. How many cells flagged were poisonous
    flagged_poisonous = len(true_positives)

    # 3. How many poisonous cells are corrected to the TRUE label (Perfect Recovery)
    perfect_recovery = true_positives[true_positives["predicted_label"] == true_positives["true_label"]]
    num_perfect_recovery = len(perfect_recovery)

    # 4. How many poisonous cells were corrected to the WRONG label (Miscorrection)
    wrong_recovery = true_positives[true_positives["predicted_label"] != true_positives["true_label"]]
    num_wrong_recovery = len(wrong_recovery)

    # 5. How many non-poisonous cells are corrected? (False Positives)
    num_clean_flagged = len(false_positives)

    # --- Print the granular report ---
    print(f"Total Flagged as Suspicious:           {total_flagged}")
    print(f"  -> Flagged cells that WERE poisonous: {flagged_poisonous}")
    print(f"       - Recovered to TRUE label:       {num_perfect_recovery}")
    print(f"       - Corrected to WRONG label:      {num_wrong_recovery}")
    print(f"  -> Flagged cells that were CLEAN:     {num_clean_flagged} (Potential Latent Errors)")
    
    # Catch Rate
    catch_rate = (len(true_positives) / total_poisoned) * 100 if total_poisoned > 0 else 0
    print(f"Catch Rate (Sensitivity):  {catch_rate:.1f}% ({len(true_positives)}/{total_poisoned} poisoned cells caught)")
    
    # False Positive Rate
    fp_rate = (len(false_positives) / total_clean) * 100 if total_clean > 0 else 0
    print(f"False Positive Rate:       {fp_rate:.1f}% ({len(false_positives)}/{total_clean} clean cells falsely flagged)")
    
    # Recovery Rate
    recovery_rate = (len(perfect_recovery) / len(true_positives)) * 100 if len(true_positives) > 0 else 0
    print(f"Recovery Rate:             {recovery_rate:.1f}% ({len(perfect_recovery)}/{len(true_positives)} caught cells restored to true label)")
    print(f"{'='*50}\n")

if __name__ == "__main__":
    main()